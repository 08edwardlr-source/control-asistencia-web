create or replace function public.es_admin()
returns boolean language sql stable security definer set search_path = '' as $$
  select exists (
    select 1 from public.usuarios_almacenes
    where usuario_id = (select auth.uid()) and rol = 'administrador' and activo
  );
$$;

create or replace function public.tiene_acceso_almacen(p_almacen_id uuid)
returns boolean language sql stable security definer set search_path = '' as $$
  select exists (
    select 1 from public.usuarios_almacenes
    where usuario_id = (select auth.uid()) and almacen_id = p_almacen_id and activo
  );
$$;

create or replace function public.puede_editar_almacen(p_almacen_id uuid)
returns boolean language sql stable security definer set search_path = '' as $$
  select exists (
    select 1 from public.usuarios_almacenes
    where usuario_id = (select auth.uid()) and almacen_id = p_almacen_id
      and rol in ('administrador','supervisor') and activo
  );
$$;

revoke all on function public.es_admin() from public;
revoke all on function public.tiene_acceso_almacen(uuid) from public;
revoke all on function public.puede_editar_almacen(uuid) from public;
grant execute on function public.es_admin() to authenticated;
grant execute on function public.tiene_acceso_almacen(uuid) to authenticated;
grant execute on function public.puede_editar_almacen(uuid) to authenticated;

create or replace function public.crear_perfil_nuevo_usuario()
returns trigger language plpgsql security definer set search_path = '' as $$
declare
  v_almacen uuid;
  v_nombre text;
  v_es_admin boolean;
  v_permisos jsonb;
begin
  v_nombre := coalesce(nullif(trim(new.raw_user_meta_data ->> 'nombre'), ''), split_part(new.email, '@', 1));
  select exists (
    select 1 from public.administradores_iniciales
    where lower(email) = lower(new.email) and activo
  ) into v_es_admin;

  v_permisos := case when v_es_admin then
    '{"editar":true,"administrar":true,"tabs":["asistencia","historial","programacion","trabajadores","reportes","ajustes","perfil"]}'::jsonb
  else
    '{"editar":false,"administrar":false,"tabs":["asistencia","historial","reportes","perfil"]}'::jsonb
  end;

  insert into public.perfiles (id, nombre, permisos)
  values (new.id, v_nombre, v_permisos)
  on conflict (id) do update set nombre = excluded.nombre, actualizado_en = now();

  begin
    v_almacen := nullif(new.raw_user_meta_data ->> 'almacen_solicitado_id', '')::uuid;
  exception when invalid_text_representation then v_almacen := null;
  end;
  if v_almacen is null then
    select id into v_almacen from public.almacenes where activo order by creado_en limit 1;
  end if;

  if v_almacen is not null then
    insert into public.usuarios_almacenes (usuario_id, almacen_id, rol, activo)
    values (new.id, v_almacen, case when v_es_admin then 'administrador' else 'lector' end, true)
    on conflict (usuario_id, almacen_id) do update set rol = excluded.rol, activo = true;
  end if;
  return new;
end;
$$;

drop trigger if exists al_crear_usuario on auth.users;
create trigger al_crear_usuario after insert on auth.users
for each row execute function public.crear_perfil_nuevo_usuario();

