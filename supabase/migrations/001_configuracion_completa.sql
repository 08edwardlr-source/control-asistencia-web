insert into public.perfiles (id, nombre, permisos)
select u.id,
  coalesce(nullif(trim(u.raw_user_meta_data ->> 'nombre'), ''), split_part(u.email, '@', 1)),
  case when exists (
    select 1 from public.administradores_iniciales ai
    where lower(ai.email) = lower(u.email) and ai.activo
  ) then '{"editar":true,"administrar":true,"tabs":["asistencia","historial","programacion","trabajadores","reportes","ajustes","perfil"]}'::jsonb
  else '{"editar":false,"administrar":false,"tabs":["asistencia","historial","reportes","perfil"]}'::jsonb end
from auth.users u
on conflict (id) do update set nombre = excluded.nombre, permisos = excluded.permisos, actualizado_en = now();

insert into public.usuarios_almacenes (usuario_id, almacen_id, rol, activo)
select u.id, a.id,
  case when exists (
    select 1 from public.administradores_iniciales ai
    where lower(ai.email) = lower(u.email) and ai.activo
  ) then 'administrador' else 'lector' end, true
from auth.users u
cross join lateral (select id from public.almacenes where activo order by creado_en limit 1) a
on conflict (usuario_id, almacen_id) do update set rol = excluded.rol, activo = true;

