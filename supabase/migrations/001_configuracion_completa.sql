create extension if not exists pgcrypto;

create table if not exists public.almacenes (
  id uuid primary key default gen_random_uuid(),
  codigo text not null unique,
  nombre text not null,
  activo boolean not null default true,
  creado_en timestamptz not null default now()
);

create table if not exists public.perfiles (
  id uuid primary key references auth.users(id) on delete cascade,
  nombre text not null default '',
  permisos jsonb not null default '{"editar":false,"administrar":false,"tabs":["asistencia","historial","reportes","perfil"]}'::jsonb,
  creado_en timestamptz not null default now(),
  actualizado_en timestamptz not null default now()
);

create table if not exists public.administradores_iniciales (
  email text primary key,
  nombre text not null,
  activo boolean not null default true,
  creado_en timestamptz not null default now()
);

create table if not exists public.usuarios_almacenes (
  usuario_id uuid not null references auth.users(id) on delete cascade,
  almacen_id uuid not null references public.almacenes(id) on delete cascade,
  rol text not null default 'lector' check (rol in ('administrador','supervisor','lector')),
  activo boolean not null default true,
  creado_en timestamptz not null default now(),
  primary key (usuario_id, almacen_id)
);

create table if not exists public.solicitudes_almacen (
  id bigint generated by default as identity primary key,
  usuario_id uuid not null references auth.users(id) on delete cascade,
  almacen_id uuid not null references public.almacenes(id) on delete cascade,
  estado text not null default 'pendiente' check (estado in ('pendiente','aprobada','rechazada')),
  creado_en timestamptz not null default now(),
  actualizado_en timestamptz not null default now(),
  unique (usuario_id, almacen_id)
);

create table if not exists public.estado_almacen (
  almacen_id uuid not null references public.almacenes(id) on delete cascade,
  clave text not null,
  datos jsonb not null default 'null'::jsonb,
  actualizado_por uuid references auth.users(id) on delete set null,
  actualizado_en timestamptz not null default now(),
  primary key (almacen_id, clave)
);

create table if not exists public.asistencias_almacen (
  almacen_id uuid not null references public.almacenes(id) on delete cascade,
  id text not null,
  propietario_id uuid references auth.users(id) on delete set null,
  fecha date not null,
  dni text not null default '',
  trabajador text not null default '',
  turno_id text not null default '',
  turno text not null default '',
  entrada time,
  salida time,
  horas_trabajadas_minutos integer check (horas_trabajadas_minutos is null or horas_trabajadas_minutos >= 0),
  metodo text,
  metodo_salida text,
  estado_entrada text,
  estado_salida text,
  supervisor text,
  finalizado boolean not null default false,
  cierre_id text,
  minutos_salida_anticipada integer not null default 0 check (minutos_salida_anticipada >= 0),
  datos_extra jsonb not null default '{}'::jsonb,
  actualizado_en timestamptz not null default now(),
  primary key (almacen_id, id)
);

create index if not exists idx_usuarios_almacenes_usuario on public.usuarios_almacenes(usuario_id);
create index if not exists idx_solicitudes_usuario on public.solicitudes_almacen(usuario_id);
create index if not exists idx_asistencias_fecha on public.asistencias_almacen(almacen_id, fecha);
create index if not exists idx_asistencias_dni on public.asistencias_almacen(almacen_id, dni);
create index if not exists idx_asistencias_finalizado on public.asistencias_almacen(almacen_id, finalizado);

